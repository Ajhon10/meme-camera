export type GestureId = (typeof gestureOptions)[number]['id']
export type GestureScores = Record<GestureId, number>
export const gestureName = (id: string) =>
  gestureOptions.find((gesture) => gesture.id === id)?.name ?? id
export const gestureDetails = (id: string) => gestureOptions.find((gesture) => gesture.id === id)
export function emptyScores(): GestureScores {
  return Object.fromEntries(gestureOptions.map(({ id }) => [id, 0])) as GestureScores
}
export function missingDetectors(id: string, enabled: DetectorSettings): string[] {
  return gestureDetails(id)?.detectors.filter((detector) => !enabled[detector]) ?? []
}
